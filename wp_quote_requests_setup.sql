-- White Pack public catalogue quotation requests
-- Run once in Supabase SQL Editor for project gaphiedcwueunmfssisz.
-- This table is separate from confirmed orders and never changes wp_products stock.

create table if not exists public.wp_quote_requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  delivery_address text,
  notes text,
  items jsonb not null default '[]'::jsonb,
  total numeric(14,2) not null default 0,
  currency text not null default 'USD',
  status text not null default 'new',
  source text not null default 'public_catalogue',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  admin_notes text
);

create index if not exists wp_quote_requests_created_at_idx
  on public.wp_quote_requests (created_at desc);
create index if not exists wp_quote_requests_status_idx
  on public.wp_quote_requests (status);

alter table public.wp_quote_requests enable row level security;

drop policy if exists "Public can submit quotation requests" on public.wp_quote_requests;
create policy "Public can submit quotation requests"
  on public.wp_quote_requests for insert to anon, authenticated
  with check (
    length(trim(customer_name)) between 1 and 120
    and length(trim(customer_phone)) between 1 and 40
    and jsonb_typeof(items) = 'array'
    and jsonb_array_length(items) > 0
  );

drop policy if exists "Authenticated staff can read quotation requests" on public.wp_quote_requests;
create policy "Authenticated staff can read quotation requests"
  on public.wp_quote_requests for select to authenticated
  using (auth.uid() is not null);

drop policy if exists "Authenticated staff can update quotation requests" on public.wp_quote_requests;
create policy "Authenticated staff can update quotation requests"
  on public.wp_quote_requests for update to authenticated
  using (auth.uid() is not null)
  with check (auth.uid() is not null);

grant insert on public.wp_quote_requests to anon, authenticated;
grant select, update on public.wp_quote_requests to authenticated;
grant usage on sequence public.wp_quote_requests_request_number_seq to anon, authenticated;
